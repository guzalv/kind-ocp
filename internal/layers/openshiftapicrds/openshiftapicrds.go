// crdURL builds the fetch URL for one CRD manifest at the given commit.
// The commit must be a full 40-hex SHA and the path a plain relative
// module path — both are generated or pinned constants here, and
// anything else is a generation bug to refuse, not a URL to try: a
// shortened ref would hand the choice of commit to GitHub's resolver,
// and a path with separators or URL metacharacters could address
// something other than the pinned manifest. path.Clean — not
// filepath.Clean — because this is a slash-separated module path, not
// an operating-system path.
func crdURL(commit, modulePath string) (string, error) {
	if !commitPattern.MatchString(commit) {
		return "", fmt.Errorf("invalid openshift/api commit %q: must be a full 40-hex SHA — regenerate the pin file (go generate ./internal/layers/openshiftapicrds)", commit)
	}
	if modulePath == "" || strings.HasPrefix(modulePath, "/") || strings.Contains(modulePath, "..") ||
		strings.ContainsAny(modulePath, "?#") || modulePath != path.Clean(modulePath) {
		return "", fmt.Errorf("invalid openshift/api manifest path %q: must be a plain relative module path", modulePath)
	}
	return rawBaseURL + "/" + commit + "/" + modulePath, nil
}

// sourceNames returns the CRD names in table order — what the
// Established wait polls and Verify reads, in the order the CRDs are
// applied.
func sourceNames(sources []CRDSource) []string {
	names := make([]string, 0, len(sources))
	for _, s := range sources {
		names = append(names, s.Name)
	}
	return names
}

// Layer installs the real openshift/api platform CRDs. It is stateless;
// construct once.
type Layer struct{}

// Name returns "openshift-api-crds".
func (Layer) Name() string { return Name }

// Apply converges the cluster to the pinned openshift/api CRDs: load
// the 18 manifests from the layer's content cache — fetching the
// missing or corrupt entries from the pinned commit on a cache miss —
// server-side apply them, then wait for all 18 to be Established. The
// apply runs under the same field manager as every kind-ocp apply,
// with force, so superseding the config-openshift placeholders (and
// converging a placeholder that replaced a real CRD) is one apply, and
// a re-run is a no-op, exactly like every other layer.
func (l Layer) Apply(ctx context.Context, env layers.Env) error {
	crds, cached, err := loadCRDs(ctx, env, http.DefaultTransport)
	if err != nil {
		return err
	}
	env.Log.Info("applying the openshift/api platform CRDs",
		"crds", len(crds), "commit", ModuleCommit, "fromCache", cached)

	client, err := kube.NewClient(env.KubeconfigPath)
	if err != nil {
		return fmt.Errorf("building Kubernetes clients: %w", err)
	}
	if err := client.Apply(ctx, kube.LayerFieldManager(Name), crds); err != nil {
		return fmt.Errorf("applying the openshift/api CRDs: %w", err)
	}
	// No object of the CRDs' kinds may be applied before this passes
	// (the ported gotcha every layer that installs CRs shares): the
	// apiserver rejects objects of a kind whose CRD is not established,
	// and the platform-objects layer that follows applies singletons of
	// these kinds.
	if err := kube.WaitForCRDsEstablished(ctx, client.Dynamic, crdEstablishedTimeout, sourceNames(CRDSources)); err != nil {
		return fmt.Errorf("waiting for the openshift/api CRDs: %w", err)
	}
	return nil
}

// realCRDAnnotation is the api-approved.openshift.io review stamp every
// published openshift/api CRD carries and no config-openshift
// placeholder does. It is documentation of the two manifests'
// provenance, observed independently by the integration tests — but it
// is deliberately not Verify's realness check: an annotation is
// metadata a schema-only change leaves untouched, so trusting it let a
// placeholder that carried the marker pass. Verify reads the served
// schema instead (realCRDSchema).
const realCRDAnnotation = "api-approved.openshift.io"

// Verify checks the layer's postconditions and mutates nothing: all 18
// CRDs exist, report Established, and carry the real openshift/api
// schema. Established alone does not distinguish them (placeholders
// establish too, so an Established-only check would pass a downgraded
// cluster), and neither does the
// api-approved.openshift.io annotation (a schema-only change leaves it
// untouched); the root schemas the
// cluster actually serves are the check. The read is bounded by
// readTimeout.
func (l Layer) Verify(ctx context.Context, env layers.Env) error {
	return l.verify(ctx, env, readTimeout)
}

// verify is Verify with an explicit read budget. Verify passes the
// production bound (readTimeout); the bounded-read regression test
// drives this helper with a short budget, which is why the budget is a
// parameter and not a setting.
func (l Layer) verify(ctx context.Context, env layers.Env, readBudget time.Duration) error {
	client, err := kube.NewClient(env.KubeconfigPath)
	if err != nil {
		return fmt.Errorf("building Kubernetes clients: %w", err)
	}
	// The reads run under a deadline context: the caller's context can
	// be unbounded (the CLI passes context.Background), so an
	// apiserver that wedges a response must not outlive the budget.
	readCtx, cancel := context.WithTimeout(ctx, readBudget)
	defer cancel()
	var problems []string
	for _, name := range sourceNames(CRDSources) {
		crd, err := kube.ReadCRD(readCtx, client.Dynamic, name)
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s: %v", name, err))
			continue
		}
		if established, why := kube.CRDEstablished(crd); !established {
			problems = append(problems, fmt.Sprintf("%s: not Established (%s)", name, why))
			continue
		}
		if real, why := realCRDSchema(crd); !real {
			problems = append(problems, fmt.Sprintf(
				"%s: %s — it is not the real openshift/api CRD (a config-openshift placeholder is installed under the name); re-run create to converge the real CRDs",
				name, why))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("%d of %d openshift/api CRDs failed their check: %s (was the %s layer applied?)",
			len(problems), len(CRDSources), strings.Join(problems, "; "), Name)
	}
	return nil
}

// realCRDSchema reports whether crd carries the real openshift/api
// schema it is named for, and why not when it does not: every version's
// root schema defines properties and preserves no unknown fields. The
// config-openshift placeholder under the same name is the exact
// opposite — every field preserved, none defined — and no annotation or
// condition distinguishes the two, so the structural traits of what the
// cluster serves are the check. The traits are pinned against the
// pinned module at build time (TestCRDSourcesAgainstModule runs this
// very function over every module manifest), so a module bump that
// breaks the assumption fails the build, not a verify run.
func realCRDSchema(crd *unstructured.Unstructured) (real bool, why string) {
	versions, _, err := unstructured.NestedSlice(crd.Object, "spec", "versions")
	if err != nil {
		return false, fmt.Sprintf("reading spec.versions: %v", err)
	}
	if len(versions) == 0 {
		return false, "carries no versions"
	}
	for _, v := range versions {
		version, ok := v.(map[string]any)
		if !ok {
			return false, "carries a version entry that is not an object"
		}
		name, _, _ := unstructured.NestedString(version, "name")
		schema, found, err := unstructured.NestedMap(version, "schema", "openAPIV3Schema")
		if err != nil {
			return false, fmt.Sprintf("reading version %s's root schema: %v", name, err)
		}
		if !found {
			return false, fmt.Sprintf("version %s carries no root schema", name)
		}
		if preserve, found, _ := unstructured.NestedBool(schema, "x-kubernetes-preserve-unknown-fields"); found && preserve {
			return false, fmt.Sprintf("version %s's root schema preserves unknown fields (the config-openshift placeholder's shape)", name)
		}
		props, found, _ := unstructured.NestedMap(schema, "properties")
		if !found || len(props) == 0 {
			return false, fmt.Sprintf("version %s's root schema defines no properties", name)
		}
	}
	return true, ""
}

// decodeCRD decodes one manifest and checks it is exactly the CRD it
// claims to be: a single document, a CustomResourceDefinition, carrying
// the expected metadata.name. Fetched and cached bytes alike pass
// through this before anything is applied — a manifest that is not the
// pinned CRD it should be is refused, whatever put it there.
func decodeCRD(b []byte, wantName string) (*unstructured.Unstructured, error) {
	objs, err := kube.DecodeManifests(bytes.NewReader(b))
	if err != nil {
		return nil, err
	}
	if len(objs) != 1 {
		return nil, fmt.Errorf("expected exactly one object, got %d", len(objs))
	}
	obj := objs[0]
	if obj.GetKind() != "CustomResourceDefinition" {
		return nil, fmt.Errorf("expected a CustomResourceDefinition, got kind %q", obj.GetKind())
	}
	if obj.GetName() != wantName {
		return nil, fmt.Errorf("expected the CRD %q, got %q", wantName, obj.GetName())
	}
	return obj, nil
}
