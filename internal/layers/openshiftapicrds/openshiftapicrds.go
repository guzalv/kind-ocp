// Package openshiftapicrds implements the openshift-api-crds layer: the
// 18 real OpenShift platform CRDs — the config.openshift.io,
// operator.openshift.io, and security.openshift.io groups — that the
// Compliance Operator's ocp4 checks read and that the platform-objects
// layer builds its singletons and SCCs on.
//
// Ported from the PoC's stage_openshift_crds with OPENSHIFT_CRD_MAP
// (stackrox PR #23841). The config-openshift layer already applied
// placeholder CRDs under these names; this layer supersedes them with
// the real schemas, which is why it registers after config-openshift
// (the real CRDs replace the placeholders) and before platform-objects
// (SCCs only validate against the real security.openshift.io CRD).
//
// Sourcing (docs/PLAN.md §2, locked decision): no committed CRD copies.
// The github.com/openshift/api module this repo's go.mod pins is the
// single source of truth for which CRDs these are. A generated pin file
// (pin_gen.go, regenerated by tools/pin-openshift-api — see pin.go)
// embeds the module's version, its commit, and the expected SHA-256 of
// every one of the 18 manifests as it exists in that module. Apply
// fetches the manifests over HTTPS from exactly that commit into a
// per-state-root cache keyed by the commit (layers.Env.CacheDir), so
// the prefix's clusters share one fetch and a re-create after delete
// reuses it. Nothing is read from a Go checkout or module cache at
// runtime: the binary works from `go install` with only Docker and
// network present (AC-6.4), like the rest of kind-ocp.
//
// The layer deliberately has no settings. Its one pin — which
// openshift/api commit to fetch — is a build-time decision owned by
// go.mod. This is the one ratified exception to AC-4.3 ("every runtime
// pin is overridable through config"), recorded by the po node on
// 2026-11-20: the pin addresses immutable content (a full commit SHA
// on raw.githubusercontent.com does not drift), so an operational
// escape hatch has no use case, and a runtime knob would add a second,
// unvalidated pin source exactly where AC-3.4 makes go.mod the single
// source of truth. Overriding it means bumping go.mod and regenerating
// the pin file (`make generate`) — never a config knob.
//
// Bytes that reach cluster-admin apply are never trusted because they
// are on disk: every cache read and every download is validated
// against the build-time expected digest for its CRD, every manifest
// is checked to be exactly the CRD it claims to be, every cache read
// is bounded by the largest pinned manifest, and only a missing or
// corrupt entry is fetched and atomically replaced (see cache.go).
// The digests are generated from the pinned module, so they bind the
// cached and fetched bytes to go.mod's pin — not to anything the cache
// or the network says about itself.
//
// Waits are bounded by fixed budgets, not settings: AC-3.1 requires
// bounded waits, and no documented use case overrides a budget. The
// Established wait is bounded by crdEstablishedTimeout; Verify's read
// by readTimeout.
package openshiftapicrds

